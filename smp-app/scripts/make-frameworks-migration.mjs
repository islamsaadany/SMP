/* Writes db/migrations/010-the-eighty-frameworks.sql from the Strategic
   Decision Toolkit's own dataset (spec 052, task A5).
 *
 * RUN BY HAND, ONCE. Its OUTPUT is the artefact and the thing under review;
 * this file is how that output was made, kept so it can be audited and so a
 * correction is a re-run rather than eighty hand edits.
 *
 * IT IS NOT A BUILD STEP AND MUST NOT BECOME ONE. Once the eighty are in the
 * table they are the library — admins edit them — and a generator wired into
 * the build would be a second opinion about what the library holds (§53.5).
 * The toolkit repository is a historical source from that moment, not a copy
 * to keep in step.
 *
 *   node scripts/make-frameworks-migration.mjs <path to tools.json>
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2];
if (!src) { console.error("usage: make-frameworks-migration.mjs <path to tools.json>"); process.exit(1); }

const rows = JSON.parse(readFileSync(src, "utf8"));

/* The nine content fields plus the three that address the row, in the order
   the table declares them. Named here rather than taken from the first record
   with Object.keys: a dataset that gained a field would then silently change
   the shape of the insert. */
const FIELDS = [
  ["idx", "id"], ["slug", "slug"], ["name", "name"], ["section", "section"],
  ["purpose", "purpose"], ["key_questions", "keyQuestions"],
  ["when_to_use", "whenToUse"], ["when_not_to_use", "whenNotToUse"],
  ["inputs_required", "inputsRequired"], ["outputs", "outputs"],
  ["executive_example", "executiveExample"],
  ["consultant_use_case", "consultantUseCase"],
  ["facilitation_tips", "facilitationTips"],
];

/* REFUSE RATHER THAN WRITE SOMETHING SUBTLY WRONG (§54.5: a generator that
   writes what it has when it could not do the job produces a plausible
   artefact). Three ways the dataset can be unusable, each named. */
if (!Array.isArray(rows) || !rows.length) { console.error("no rows in " + src); process.exit(1); }
const seen = new Set();
for (const r of rows) {
  for (const [col, key] of FIELDS) {
    if (col === "idx") { if (!/^\d+$/.test(String(r[key]))) { console.error("row " + r.id + ": idx is not a number"); process.exit(1); } continue; }
    if (typeof r[key] !== "string") { console.error("row " + r.id + ": " + key + " is not text"); process.exit(1); }
    if (col === "name" && !r[key].trim()) { console.error("row " + r.id + ": no name"); process.exit(1); }
  }
  if (seen.has(r.slug)) { console.error("two rows want the slug " + r.slug); process.exit(1); }
  seen.add(r.slug);
}

/* Standard SQL escaping, and it is the only escaping needed: Postgres runs
   with standard_conforming_strings on, so a backslash is a backslash and the
   single quote is the whole of it. The dataset carries curly quotes, en-dashes
   and × — all of them ordinary UTF-8 text, which is why this file is written
   as UTF-8 and read as UTF-8 and nothing transliterates. */
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
/* `idx` is the dataset's own 1–80, which IS the book's order — written as a
   number, never quoted, so the column keeps its type. */
const val = (col, v) => (col === "idx" ? String(Number(v)) : q(v));

const head = `/* The eighty frameworks the library ships with (spec 052, task A6).

   GENERATED by scripts/make-frameworks-migration.mjs — do not hand-edit; if
   these need correcting, correct them in the library, which is where they
   live once this has run.

   Source: islamsaadany/strategic-decision-toolkit at 12089e9,
   lib/data/tools.json — ${rows.length} frameworks, ${new Set(rows.map((r) => r.section)).size} sections, every field filled.

   \`added_by\` IS LEFT NULL ON ALL ${rows.length}, which is what "came with the library"
   means (§35): nobody here wrote them, and inventing an author to fill the
   column would put a name on work that is not theirs.

   \`ON CONFLICT (slug) DO NOTHING\` is belt and braces in the SAFE direction.
   _migrations already guarantees this runs once, so the clause should never
   fire — and if it ever did, doing nothing protects an entry an admin has
   since corrected, where a plain INSERT would fail the whole deploy and an
   upsert would quietly restore the original. */
`;

const cols = FIELDS.map(([c]) => c).join(", ");
const body = rows.map((r) =>
  "INSERT INTO frameworks (" + cols + ") VALUES\n  (" +
  FIELDS.map(([c, k]) => val(c, r[k])).join(", ") + ")\n  ON CONFLICT (slug) DO NOTHING;"
).join("\n");

const out = join(here, "..", "db", "migrations", "010-the-eighty-frameworks.sql");
writeFileSync(out, head + "\n" + body + "\n", "utf8");
console.log("wrote " + out + " — " + rows.length + " frameworks, " + new Set(rows.map((r) => r.section)).size + " sections");
